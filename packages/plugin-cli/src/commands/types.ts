import { readFile, mkdir, writeFile } from 'node:fs/promises';
import path from 'node:path';

import { settingSchema, settingsSchema, type Setting } from '@vtt/plugin-schema';

import type { Output } from '../io.js';

// `vtt-plugin types` (T-1611): plugin code gets its settings as untyped values
// (`useModuleSettings`), so the command writes a module with the settings' type and a reader
// that types them, falling back to the defaults, without casts.

const WIDTH = 100;

const quote = (text: string): string => `'${text.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;

/** `const name = [...] as const;`, on one line when it fits, else one value per line. */
function constList(name: string, values: readonly string[]): string {
  const line = `const ${name} = [${values.map(quote).join(', ')}] as const;`;
  if (line.length <= WIDTH) return line;
  return [`const ${name} = [`, ...values.map((value) => `  ${quote(value)},`), `] as const;`].join(
    '\n',
  );
}

const READERS = {
  pick: [
    'const pick = <T extends string>(value: unknown, options: readonly T[], fallback: T): T =>',
    '  options.find((option) => option === value) ?? fallback;',
  ],
  text: [
    'const text = (value: unknown, fallback: string): string =>',
    "  typeof value === 'string' ? value : fallback;",
  ],
  number: [
    'const number = (value: unknown, fallback: number): number =>',
    "  typeof value === 'number' && Number.isFinite(value) ? value : fallback;",
  ],
  flag: [
    'const flag = (value: unknown, fallback: boolean): boolean =>',
    "  typeof value === 'boolean' ? value : fallback;",
  ],
} as const;

interface Field {
  type: string;
  read: string;
  reader: keyof typeof READERS;
  list?: string;
}

function field(name: string, setting: Setting): Field {
  const value = `values.${name}`;
  switch (setting.type) {
    case 'boolean':
      return {
        type: 'boolean',
        read: `flag(${value}, ${String(setting.default)})`,
        reader: 'flag',
      };
    case 'integer':
    case 'number':
      return {
        type: 'number',
        read: `number(${value}, ${String(setting.default)})`,
        reader: 'number',
      };
    case 'string': {
      if (setting.enum === undefined)
        return {
          type: 'string',
          read: `text(${value}, ${quote(setting.default)})`,
          reader: 'text',
        };
      const list = `${name}Values`;
      return {
        type: `(typeof ${list})[number]`,
        read: `pick(${value}, ${list}, ${quote(setting.default)})`,
        reader: 'pick',
        list: constList(list, setting.enum),
      };
    }
  }
}

/** The settings module for a plugin's `settings.json` (T-1611); it needs one setting or more. */
export function settingsModule(settings: Readonly<Record<string, Setting>>): string {
  const fields = Object.entries(settings).map(([name, setting]) => ({
    name,
    setting,
    ...field(name, setting),
  }));
  const readers = new Set(fields.map((each) => each.reader));
  const lists = fields.flatMap((each) => (each.list === undefined ? [] : [each.list]));
  const lines = [
    '// Generated by `vtt-plugin types` from settings.json: run it again after changing the',
    '// settings instead of editing this file.',
    '',
    ...(lists.length > 0 ? [...lists, ''] : []),
    '/** The plugin’s settings, typed. */',
    'export interface Settings {',
    ...fields.flatMap(({ name, setting, type }) => [
      `  /** ${setting.label} (${setting.scope ?? 'table'}). */`,
      `  ${name}: ${type};`,
    ]),
    '}',
    '',
    ...(Object.keys(READERS) as (keyof typeof READERS)[])
      .filter((reader) => readers.has(reader))
      .flatMap((reader) => READERS[reader]),
    ...(readers.size > 0 ? [''] : []),
    '/**',
    ' * The settings from the values the host gives (`useModuleSettings`), typed: a value that does',
    ' * not fit its setting gives the default.',
    ' */',
    'export function readSettings(values: Readonly<Record<string, unknown>>): Settings {',
    '  return {',
    ...fields.map(({ name, read }) => `    ${name}: ${read},`),
    '  };',
    '}',
    '',
  ];
  return lines.join('\n');
}

/** The settings of a `settings.json`'s text, by name; `undefined` when it does not fit. */
export function settingsOf(source: string): Record<string, Setting> | undefined {
  const parsed = settingsSchema.safeParse(JSON.parse(source));
  if (!parsed.success) return undefined;
  const settings: Record<string, Setting> = {};
  for (const [name, value] of Object.entries(parsed.data)) {
    const setting = settingSchema.safeParse(value);
    if (name !== '$schema' && setting.success) settings[name] = setting.data;
  }
  return settings;
}

/** `vtt-plugin types <dir> [--out <file>]`: writes the settings module, by default to code/src. */
export async function typesCommand(
  dir: string,
  out: string | undefined,
  output: Output,
): Promise<number> {
  const source = await readFile(path.join(dir, 'settings.json'), 'utf8');
  const settings = settingsOf(source);
  if (!settings) {
    output.err('settings.json is not valid: run `vtt-plugin validate` to see why.');
    return 1;
  }
  if (Object.keys(settings).length === 0) {
    output.err('settings.json has no settings to type.');
    return 1;
  }
  const file = out ?? path.join(dir, 'code', 'src', 'settings.ts');
  await mkdir(path.dirname(file), { recursive: true });
  await writeFile(file, settingsModule(settings));
  output.out(`Wrote the settings types to ${file}`);
  return 0;
}
